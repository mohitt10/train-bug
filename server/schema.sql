-- WanderLog database schema
-- Database: PostgreSQL
--
-- Implementation conventions:
--   1. DATETIME from the relational diagram is represented as TIMESTAMPTZ.
--   2. Standalone integer primary keys use identity generation.
--   3. created_at columns default to the current timestamp.
--   4. Foreign keys use the default NO ACTION deletion behaviour.
--
-- Run this script once against an empty database.

-- =========================================================
-- 1. USERS
-- =========================================================

CREATE TABLE users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(100),
    bio VARCHAR(500),
    account_status VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ
);

-- =========================================================
-- 2. MODERATORS
-- =========================================================

CREATE TABLE moderators (
    user_id INT PRIMARY KEY,
    moderator_since TIMESTAMPTZ,

    CONSTRAINT fk_moderators_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
);

-- =========================================================
-- 3. FOLLOWS
-- =========================================================

CREATE TABLE follows (
    follower_id INT NOT NULL,
    following_id INT NOT NULL,
    followed_at TIMESTAMPTZ,

    PRIMARY KEY (follower_id, following_id),

    CONSTRAINT fk_follows_follower
        FOREIGN KEY (follower_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_follows_following
        FOREIGN KEY (following_id)
        REFERENCES users(user_id),

    CONSTRAINT chk_no_self_follow
        CHECK (follower_id <> following_id)
);

-- =========================================================
-- 4. POSTS
-- =========================================================

CREATE TABLE posts (
    post_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    title VARCHAR(200),
    content TEXT,
    location VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ,

    CONSTRAINT fk_posts_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
);

-- =========================================================
-- 5. COMMENTS
-- =========================================================

CREATE TABLE comments (
    comment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    post_id INT NOT NULL,
    content VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ,

    CONSTRAINT fk_comments_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_comments_post
        FOREIGN KEY (post_id)
        REFERENCES posts(post_id)
);

-- =========================================================
-- 6. REPLIES
-- =========================================================

CREATE TABLE replies (
    reply_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    comment_id INT NOT NULL,
    content VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ,

    CONSTRAINT fk_replies_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_replies_comment
        FOREIGN KEY (comment_id)
        REFERENCES comments(comment_id)
);

-- =========================================================
-- 7. POST LIKES
-- =========================================================

CREATE TABLE post_likes (
    user_id INT NOT NULL,
    post_id INT NOT NULL,
    liked_at TIMESTAMPTZ,

    PRIMARY KEY (user_id, post_id),

    CONSTRAINT fk_post_likes_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_post_likes_post
        FOREIGN KEY (post_id)
        REFERENCES posts(post_id)
);

-- =========================================================
-- 8. COMMENT LIKES
-- =========================================================

CREATE TABLE comment_likes (
    user_id INT NOT NULL,
    comment_id INT NOT NULL,
    liked_at TIMESTAMPTZ,

    PRIMARY KEY (user_id, comment_id),

    CONSTRAINT fk_comment_likes_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_comment_likes_comment
        FOREIGN KEY (comment_id)
        REFERENCES comments(comment_id)
);

-- =========================================================
-- 9. REPORTS
-- =========================================================

CREATE TABLE reports (
    report_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id INT NOT NULL,
    reason VARCHAR(500),
    status VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    post_id INT,
    comment_id INT,
    reply_id INT,
    reviewed_by INT,

    CONSTRAINT fk_reports_reporter
        FOREIGN KEY (reporter_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_reports_post
        FOREIGN KEY (post_id)
        REFERENCES posts(post_id),

    CONSTRAINT fk_reports_comment
        FOREIGN KEY (comment_id)
        REFERENCES comments(comment_id),

    CONSTRAINT fk_reports_reply
        FOREIGN KEY (reply_id)
        REFERENCES replies(reply_id),

    CONSTRAINT fk_reports_moderator
        FOREIGN KEY (reviewed_by)
        REFERENCES moderators(user_id),

    CONSTRAINT chk_report_exactly_one_target
        CHECK (
            (post_id IS NOT NULL AND comment_id IS NULL AND reply_id IS NULL)
            OR
            (post_id IS NULL AND comment_id IS NOT NULL AND reply_id IS NULL)
            OR
            (post_id IS NULL AND comment_id IS NULL AND reply_id IS NOT NULL)
        )
);
